// Generates src/face-mesh-data.js from MediaPipe's canonical face model.
//
//   node tools/gen-face-mesh.mjs <canonical_face_model.obj> <vision_bundle.mjs> > src/face-mesh-data.js
//
// Inputs (Apache-2.0, Google MediaPipe):
//   mediapipe/modules/face_geometry/data/canonical_face_model.obj
//   @mediapipe/tasks-vision vision_bundle.mjs (FaceLandmarker contour connections)
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const [objPath, bundlePath] = process.argv.slice(2);
const obj = readFileSync(objPath, "utf8").split("\n");
const vt = obj.filter((l) => l.startsWith("vt ")).map((l) => l.split(/\s+/).slice(1, 3).map(Number));
const faces = obj.filter((l) => l.startsWith("f ")).map((l) => l.split(/\s+/).slice(1, 4).map((p) => p.split("/").map((n) => Number(n) - 1)));

// v and vt are listed in different orders: the UV of landmark i comes from the face records.
const uv = new Array(468);
for (const f of faces) for (const [v, t] of f) uv[v] = [vt[t][0], 1 - vt[t][1]]; // flip V: texture rows go top→bottom
if (uv.some((x) => !x)) throw new Error("landmark without UV");
const tris = faces.flatMap((f) => f.map(([v]) => v));

const { FaceLandmarker } = await import(pathToFileURL(bundlePath).href);
const edges = (k) => FaceLandmarker[`FACE_LANDMARKS_${k}`].map((c) => [c.start, c.end]);

/** Chains an edge list into closed loops / open polylines of landmark indices. */
function chains(list) {
  const rest = list.map((e) => [...e]);
  const out = [];
  while (rest.length) {
    const line = rest.shift();
    let grew = true;
    while (grew) {
      grew = false;
      for (let i = 0; i < rest.length; i++) {
        const [a, b] = rest[i];
        if (a === line.at(-1)) { line.push(b); rest.splice(i, 1); grew = true; break; }
        if (b === line[0]) { line.unshift(a); rest.splice(i, 1); grew = true; break; }
      }
    }
    out.push(line);
  }
  return out;
}

/** Joins open chains that share both endpoints (upper + lower halves) into closed loops. */
function loops(list) {
  const c = chains(list);
  const out = [];
  while (c.length) {
    const a = c.shift();
    if (a[0] === a.at(-1)) { out.push(a); continue; }
    const j = c.findIndex((b) => new Set([b[0], b.at(-1)]).has(a[0]) && new Set([b[0], b.at(-1)]).has(a.at(-1)));
    if (j < 0) { out.push(a); continue; }
    let b = c.splice(j, 1)[0];
    if (b[0] !== a.at(-1)) b = b.reverse();
    out.push([...a, ...b.slice(1)]);
  }
  return out;
}

const r4 = (x) => Math.round(x * 1e4) / 1e4;
// outer lip loop encloses more area than the inner one
const area = (loop) => Math.abs(loop.reduce((s, i, k) => {
  const j = loop[(k + 1) % loop.length];
  return s + uv[i][0] * uv[j][1] - uv[j][0] * uv[i][1];
}, 0)) / 2;
const lips = loops(edges("LIPS")).sort((a, b) => area(b) - area(a));
const contours = {
  oval: loops(edges("FACE_OVAL"))[0],
  lipsOuter: lips[0],
  lipsInner: lips[1],
  eyeL: loops(edges("RIGHT_EYE"))[0],   // MediaPipe "right" = subject's right = image left
  eyeR: loops(edges("LEFT_EYE"))[0],
  browL: chains(edges("RIGHT_EYEBROW")),
  browR: chains(edges("LEFT_EYEBROW")),
};

console.log(`// GENERATED by tools/gen-face-mesh.mjs — do not edit.
// Canonical face mesh (468 landmarks) from Google MediaPipe, Apache License 2.0:
// https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj

/** UV (u, v) of each landmark in the canonical texture layout, v pointing down. */
export const UV = new Float32Array(${JSON.stringify(uv.flat().map(r4))});

/** ${tris.length / 3} triangles (landmark indices). */
export const TRIS = new Uint16Array(${JSON.stringify(tris)});

/** Ordered contours (landmark indices); first point repeated at the end for closed loops. */
export const CONTOURS = ${JSON.stringify(contours)};`);
